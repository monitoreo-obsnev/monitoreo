"""What MonitorEO-OBSNEV is and who funds it: the description and the acknowledgements shown by every tool (README,
command line, MCP server, R package and QGIS plugin), with the logos of the MonitorEO manual
(https://monitoreo-obsnev.github.io/manual) in the folder logos of this package."""

import os

APP = 'https://ee-ugr-default-project.projects.earthengine.app/view/monitoreo-obsnev'
MANUAL = 'https://monitoreo-obsnev.github.io/manual'
REPOSITORY = 'https://github.com/monitoreo-obsnev/monitoreo'

DESCRIPTION = {
	'en': 'MonitorEO-OBSNEV is an open monitoring tool of Essential Biodiversity Variables based on satellite sensors and '
	      'models generated by the University of Granada. It enables citizens, managers, and scientists to create maps '
	      'and graphs of key ecosystem metrics to support decision-making.',
	'es': 'MonitorEO-OBSNEV es una herramienta abierta de monitorización de Variables Esenciales de la Biodiversidad '
	      'basada en sensores satelitales y modelos generados por la Universidad de Granada. Permite a la ciudadanía, '
	      'gestores y científicos crear mapas y gráficos de métricas clave de los ecosistemas para apoyar la toma de '
	      'decisiones.',
}

ACKNOWLEDGEMENTS = {
	'en': 'MonitorEO is an output of the EVEREST Project (PID2023-151939OB-I00), funded by MICIU/AEI '
	      '10.13039/501100011033, and co-funded by ERDF – European Union, as well as of the NevadEO Project '
	      '(C-EXP-074-UGR23), co-funded by the ERDF 2014-2020 Program and the Regional Ministry of Economy, Knowledge, '
	      'Enterprise, and Universities of the Regional Government of Andalusia.',
	'es': 'MonitorEO es un resultado del Proyecto EVEREST (PID2023-151939OB-I00), financiado por MICIU/AEI '
	      '10.13039/501100011033 y cofinanciado por FEDER – Unión Europea, y del Proyecto NevadEO (C-EXP-074-UGR23), '
	      'cofinanciado por el Programa FEDER 2014-2020 y la Consejería de Economía, Conocimiento, Empresa y '
	      'Universidades de la Junta de Andalucía.',
}

_LOGOS = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'logos')
# Observatorio de Cambio Global de Sierra Nevada, Universidad de Granada, MICIU + Cofinanciado por la Unión Europea +
# AEI (EVEREST) and Junta de Andalucía; and the strip of the projects of the call UGR23 co-funded by ERDF (NevadEO)
LOGOS = [os.path.join(_LOGOS, 'monitoreo_obsnev.png'), os.path.join(_LOGOS, 'nevadeo_feder.jpg')]


def about(lang='en'):
	"""{'name', 'description', 'acknowledgements', 'logos' (paths of PNG/JPEG files), 'app', 'manual', 'repository'}
	in LANG ('en' or 'es')."""
	lang = lang if lang in DESCRIPTION else 'en'
	return {'name': 'MonitorEO-OBSNEV', 'description': DESCRIPTION[lang], 'acknowledgements': ACKNOWLEDGEMENTS[lang],
	        'logos': [p for p in LOGOS if os.path.exists(p)], 'app': APP, 'manual': MANUAL, 'repository': REPOSITORY}


def text(lang='en'):
	"""The description and the acknowledgements as plain text."""
	a = about(lang)
	return f"{a['name']}\n\n{a['description']}\n\n{a['acknowledgements']}\n\n{a['app']}\n{a['manual']}\n{a['repository']}"
