  eecu_check(s)
  invisible(p)
}

#' EECUs of Earth Engine spent this month
#'
#' EECUs (compute units of Earth Engine) spent this month, against their limit, which restarts on the first day of each
#' month. With the shared account of MonitorEO they are your research EECUs (25 EECU-hours a month, only for research):
#' when they are spent it does not compute for you until the next month, so switch to your own account
#' (\code{mo_init("<your project>")}). With your own project (the Cloud Monitoring API must be enabled in it), the
#' monthly quota of that project, against \code{limit}.
#' @param limit monthly quota of your project: EECU-hours or tier (\code{"Community"}, 150; \code{"Contributor"},
#'   1000; \code{"Partner"}, 100000; default: the variable \code{MONITOREO_EECU_LIMIT} or \code{"Community"}).
#' @param refresh ask again (the answers are kept 5 minutes).
#' @param lang language of the texts: \code{"en"} or \code{"es"}.
#' @return A list (account, name, project, used_hours, limit_hours, tier, used_percent, left_percent, month, resets,
#'   low, warning, text, bar), invisibly; prints a bar and the text, and warns when less than 10 \% are left.
#' @examples
#' \dontrun{
#' mo_init()
#' mo_eecu()
#' }
#' @export
mo_eecu <- function(limit = NULL, refresh = TRUE, lang = "en") {
  u <- services()$eecu_usage(limit, refresh, lang)
  cat(u$name, " ", u$bar, "\n", u$text, "\n", sep = "")
  if (!is.null(u$warning)) warning(u$warning, call. = FALSE)
  invisible(u)
}

# A list of Python dictionaries (rows) as a data.frame, with dates as Date and None as NA.
rows_df <- function(rows) {
  if (length(rows) == 0) return(data.frame())
  cols <- unique(unlist(lapply(rows, names)))
  df <- as.data.frame(lapply(stats::setNames(cols, cols), function(col) {
    # one value per row: the lists (e.g. fixed_filters of mo_variables) as text, "clouds, water"
    v <- lapply(rows, function(r) {
      x <- r[[col]]
      if (is.null(x)) NA else if (length(x) != 1) paste(unlist(x), collapse = ", ") else x
    })
    unlist(v)
  }), stringsAsFactors = FALSE)
  if ("date" %in% names(df)) df$date <- as.Date(df$date)
  df
}

# The themes of the data of Earth Engine outside the catalog (catalog.OTHER_THEMES), which have no variables of it, with
# the functions and arguments of R: the services say what to do in the words of every tool, and the command line
# names its own commands (cli.OTHER_THEMES), so R names its functions.
other_themes <- c(
  earth_engine = paste("any image or collection of images of Earth Engine by its ID: mo_asset(ID) describes it (its",
                       "bands, units and dates, and the arguments to compute it); then compute it with its ID as",
                       "collection (or image) and its band"),
  community = paste("the datasets of the GEE Community Catalog by its own themes: mo_community_themes() lists its",
                    "themes and mo_community() their datasets; mo_asset(ID) describes one; then compute it with its",
                    "ID as collection (or image) and its band"))

# The theme of catalog.OTHER_THEMES named THEME (its key, or its name in English or Spanish, as the services read
# them), or NULL.
other_theme <- function(theme) {
  if (is.null(theme)) return(NULL)
  low <- tolower(trimws(theme))
  for (t in reticulate::import("monitoreo.catalog", convert = TRUE)$OTHER_THEMES) {
    if (nzchar(low) && low %in% tolower(c(t$key, t$en, t$es))) return(t)
  }
  NULL
}

#' Variables of the catalog of MonitorEO
#'
#' @param sensor optional: only those of \code{"Sentinel-2"}, \code{"Landsat"}, \code{"Modis"},
