#' "intercept" or "n"; `alpha` (e.g. 0.05) keeps only the significant pixels. Earth Engine tiles (see mo_leaflet()).
#' @export
mo_trend_map <- function(region, variable, sensor, start, end, step = "annual", part = NULL, output = "slope",
